def once(text, pattern, repl, flags=0):
    found = re.findall(pattern, text, flags)
    if len(found) != 1:
        raise SystemExit(f"patch '{pattern[:50]}' matched {len(found)} times, expected 1")
    return re.sub(pattern, lambda m: repl, text, flags=flags)


def main(notebook, out):
    cells = json.load(open(notebook, encoding="utf-8"))["cells"]
    cell = next("".join(c["source"]) for c in cells if c["cell_type"] == "code" and "RUN_SCRIPT_CODE" in "".join(c["source"]))
    start = cell.index("RUN_SCRIPT_CODE = r'''") + len("RUN_SCRIPT_CODE = r'''")
    end = cell.index("'''\n", start)
    lines = cell[start:end].lstrip("\n").splitlines()

    def find(pattern, begin=0):
        for i in range(begin, len(lines)):
            if re.match(pattern, lines[i]):
                return i
        raise SystemExit(f"marker not found: {pattern}")

    cut_a = find(r"^COMPARE_IDLE = ")                 # compare HTML, job runner, Gradio helpers start here
    eta_a = find(r"^def picker_eta\(")                  # ... but this ETA helper is worth keeping
    eta_b = find(r"^# ==== Gradio UI", eta_a)
    free = find(r"^REFINE_FREE\[0\] = ")                # one start-up statement that sits inside the UI section
    kept = lines[:cut_a] + ["", ""] + lines[eta_a:eta_b] + ["", ""] + [lines[free]]
    text = "\n".join(kept) + "\n"

    text = once(text, r"^import gradio as gr\n", "", re.M)
    text = once(text, r"^os\.environ\.setdefault\(\"GRADIO_TEMP_DIR\".*\n", "", re.M)
    text = once(text, r"^OUTPUT_DIR = .*\n", PRIVATE_DIR, re.M)
    text = HEADER + text

    open(out, "w", encoding="utf-8").write(text)
    print(f"{out}: {len(text.splitlines())} lines (notebook engine {len(lines)} lines; "
          f"removed {cut_a_end(lines, cut_a, eta_a, eta_b, free)} lines of UI/jobs/tunnel)")


def cut_a_end(lines, cut_a, eta_a, eta_b, free):
    return len(lines) - (cut_a + (eta_b - eta_a) + 1)


if __name__ == "__main__":
    main(*sys.argv[1:3])
